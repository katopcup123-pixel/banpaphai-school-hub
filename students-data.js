window.BPP_STUDENTS_HELPER = {
  STORAGE_KEY: "bpp_connect_students_v1",

  loadStudents() {
    try {
      const raw = localStorage.getItem(this.STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) return parsed;
      }
    } catch (_) {}
    return window.BPP_DEFAULT_STUDENTS.map((s) => ({ ...s }));
  },

  saveStudents(list) {
    try {
      localStorage.setItem(this.STORAGE_KEY, JSON.stringify(list));
    } catch (_) {}
  },

  resetStudents() {
    const base = window.BPP_DEFAULT_STUDENTS.map((s) => ({ ...s }));
    this.saveStudents(base);
    return base;
  },

  // รองรับไฟล์ CSV จากระบบ DMC โดยตรง (ตัดเลขบัตร ปชช. 13 หลักและข้อมูลผู้ปกครองออกอัตโนมัติ)
  parseCsv(csvText) {
    const clean = String(csvText || "").replace(/^\uFEFF/, "");
    const lines = clean.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    if (!lines.length) return [];

    function splitCsvLine(line) {
      const out = [];
      let cur = "", inQ = false;
      for (let i = 0; i < line.length; i++) {
        const ch = line[i];
        if (ch === '"') {
          if (inQ && line[i + 1] === '"') { cur += '"'; i++; }
          else inQ = !inQ;
        } else if (ch === "," && !inQ) {
          out.push(cur.trim());
          cur = "";
        } else {
          cur += ch;
        }
      }
      out.push(cur.trim());
      return out;
    }

    let headerIdx = -1;
    let headers = [];
    for (let i = 0; i < Math.min(lines.length, 6); i++) {
      const cols = splitCsvLine(lines[i]);
      if (cols.some((c) => c === "ชั้น" || c === "ชื่อ" || c === "นามสกุล")) {
        headerIdx = i;
        headers = cols;
        break;
      }
    }
    if (headerIdx === -1) return [];

    const idxGrade = headers.findIndex((h) => h === "ชั้น" || h.includes("ระดับชั้น"));
    const idxRoom = headers.findIndex((h) => h === "ห้อง");
    const idxGender = headers.findIndex((h) => h === "เพศ");
    const idxPrefix = headers.findIndex((h) => h === "คำนำหน้าชื่อ" || h === "คำนำหน้า");
    const idxFirst = headers.findIndex((h) => h === "ชื่อ");
    const idxLast = headers.findIndex((h) => h === "นามสกุล");
    // DMC มีคอลัมน์ "เลขประจำตัวนักเรียน" 2 ช่อง (ช่องแรกคือเลขบัตร ปชช. 13 หลัก, ช่องหลังคือรหัสนักเรียน 4 หลัก) — เลือกช่องหลังเสมอ
    let idxCode = -1;
    for (let i = headers.length - 1; i >= 0; i--) {
      if (headers[i].includes("เลขประจำตัว") || headers[i].includes("รหัสนักเรียน")) {
        idxCode = i;
        break;
      }
    }

    const students = [];
    for (let r = headerIdx + 1; r < lines.length; r++) {
      const cols = splitCsvLine(lines[r]);
      const firstName = idxFirst >= 0 ? (cols[idxFirst] || "") : "";
      const lastName = idxLast >= 0 ? (cols[idxLast] || "") : "";
      const grade = idxGrade >= 0 ? (cols[idxGrade] || "") : "";
      if (!firstName || !grade) continue;

      let code = idxCode >= 0 ? (cols[idxCode] || "") : "";
      if (code.length >= 13) code = ""; // ห้ามเก็บเลขบัตร ปชช. 13 หลัก
      const genderRaw = idxGender >= 0 ? (cols[idxGender] || "") : "";
      const prefixRaw = idxPrefix >= 0 ? (cols[idxPrefix] || "") : "";
      const gender = genderRaw.startsWith("ญ") || prefixRaw.includes("หญิง") ? "ญ" : "ช";
      const prefix = prefixRaw || (gender === "ญ" ? "เด็กหญิง" : "เด็กชาย");
      const room = idxRoom >= 0 ? (cols[idxRoom] || "1") : "1";

      students.push({
        id: code || `stu-${Date.now()}-${r}`,
        code: code || String(students.length + 1),
        grade,
        room,
        gender,
        prefix,
        firstName,
        lastName
      });
    }
    return students;
  }
};
